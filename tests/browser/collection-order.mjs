  assert.equal((await paths())[0], "content/jobs/verwaltung-01.json", "filter switches retain the second draft");
  await page.getByRole("combobox", { name: "Bereich", exact: true }).selectOption("Beratung");
  await page.getByRole("button", { name: "Verwerfen", exact: true }).click();
  await page.getByRole("combobox", { name: "Bereich", exact: true }).selectOption("Verwaltung");
