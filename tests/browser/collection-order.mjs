  await page.getByRole("button", { name: "Verwaltung 01 nach unten", exact: true }).click();
  await page.getByRole("combobox", { name: "Bereich", exact: true }).selectOption("Beratung");
  await waitFirst(secondPath);
  await page.getByRole("combobox", { name: "Bereich", exact: true }).selectOption("");
  assert.deepEqual((await paths()).slice(-3), ["content/jobs/verwaltung-02.json", "content/jobs/verwaltung-01.json", "content/jobs/verwaltung-03.json"]);
  await page.getByRole("combobox", { name: "Bereich", exact: true }).selectOption("Beratung");
